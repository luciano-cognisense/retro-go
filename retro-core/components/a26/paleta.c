void a26_paleta(uint16_t *dest, int sistema, bool be)
{
    const uint16_t *t = TABELA[sistema ? 1 : 0];

    for (int c = 0; c < 256; c += 2) {
        uint16_t v = t[c >> 1];
        if (be)
            v = (uint16_t)((v << 8) | (v >> 8));
        dest[c] = v;
        dest[c + 1] = v;              // o bit 0 nao existe no chip
    }
}
